#!/usr/bin/env python3
"""One-time OWNER provisioning using Google Cloud IAM, not public self-registration.

The address is a login identity, NEVER a system sender or global recovery mailbox.
This script cannot send a password: the owner must verify the inbox using the
usual /admin 'Create an account or reset your password' flow.
"""
import argparse
import datetime
import hashlib
import json
import re
import subprocess
import sys
import urllib.error
import urllib.parse
import urllib.request


SYSTEM_SENDER = "service@svmrakennus.fi"


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--project", required=True)
    p.add_argument("--database", required=True)
    p.add_argument("--namespace", required=True)
    p.add_argument("--email", required=True)
    a = p.parse_args()
    email = a.email.strip().lower()
    if not re.fullmatch(r"[a-z0-9._%+-]+@[a-z0-9.-]+\.[a-z]{2,}", email) or email == SYSTEM_SENDER:
        raise ValueError("Choose a personal login email, not the corporate service sender")
    for value in (a.project, a.database, a.namespace):
        if not re.fullmatch(r"[A-Za-z0-9_()\-]{1,100}", value):
            raise ValueError("Invalid Google Cloud resource name")

    token = subprocess.check_output(["gcloud", "auth", "print-access-token", "--project", a.project], text=True).strip()
    q = urllib.parse.quote
    base = ("https://firestore.googleapis.com/v1/projects/" + q(a.project, safe="") +
            "/databases/" + q(a.database, safe="") +
            "/documents/" + q(a.namespace, safe="") + "/main/users")

    def call(url, method="GET", data=None):
        req = urllib.request.Request(url, method=method, data=data,
                                     headers={"Authorization": "Bearer " + token,
                                              "Content-Type": "application/json"})
        with urllib.request.urlopen(req, timeout=30) as response:
            return json.load(response)

    records = []
    page = ""
    while True:
        params = {"pageSize": "300"}
        if page:
            params["pageToken"] = page
        listing = call(base + "?" + urllib.parse.urlencode(params))
        records.extend(listing.get("documents", []))
        page = listing.get("nextPageToken", "")
        if not page:
            break

    key = hashlib.sha256(email.encode("utf-8")).hexdigest()
    doc_path = base + "/" + key
    existing = None
    for doc in records:
        try:
            user = json.loads(doc["fields"]["payload"]["stringValue"])
        except (KeyError, ValueError, TypeError):
            raise ValueError("Malformed Firestore user document; no change made")
        if user.get("role") == "owner" and user.get("email", "").lower() not in (email, SYSTEM_SENDER):
            raise ValueError("Another owner already exists; manage access through the Users tab")
        if doc["name"].rsplit("/", 1)[-1] == key:
            existing = (doc, user)

    timestamp = datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")
    if existing:
        doc, user = existing
        if user.get("email", "").lower() != email:
            raise ValueError("Stored email does not match user ID")
        user["role"] = "owner"
        user["status"] = "active"
        user["version"] = int(user.get("version", 0)) + 1
        user["updated"] = timestamp
        cond = {"currentDocument.updateTime": doc["updateTime"]}
    else:
        user = {
            "email": email,
            "hash": "",
            "role": "owner",
            "status": "active",
            "verified": False,
            "version": 1,
            "created": timestamp,
            "updated": timestamp,
        }
        cond = {"currentDocument.exists": "false"}
    body = json.dumps({"fields": {"payload": {"stringValue": json.dumps(user, separators=(",", ":"))}}}).encode()
    call(doc_path + "?" + urllib.parse.urlencode(cond), "PATCH", body)
    print("Owner login identity provisioned:", email)
    print("Corporate sender stays:", SYSTEM_SENDER)
    print("Now request an email confirmation/password link at https://svmrakennus.fi/admin")
    print("No email or password was generated by this command.")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, subprocess.CalledProcessError, urllib.error.URLError) as e:
        print("Owner provisioning failed:", str(e), file=sys.stderr)
        sys.exit(1)
